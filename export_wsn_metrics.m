function export_wsn_metrics(metrics, filename)
%EXPORT_WSN_METRICS Write one protocol's per-round metrics to CSV.
if nargin < 2, filename = [metrics.protocol '_metrics.csv']; end
T = table(metrics.rounds, metrics.aliveNodes, metrics.residualEnergyJ, ...
    metrics.avgResidualEnergyJ, ...
    metrics.energyConsumedPerRoundJ, ...
    metrics.cumulativeEnergyConsumedJ, ...
    metrics.packetsAtBSPerRound, metrics.packetsAtBSCumulative, ...
    'VariableNames', {'Round','AliveNodes','ResidualEnergyJ', ...
    'AvgResidualEnergyJ', ...
    'EnergyConsumedPerRoundJ', ...
    'CumulativeEnergyConsumedJ', ...
    'PacketsAtBS','CumulativePacketsAtBS'});
writetable(T, filename);
end
